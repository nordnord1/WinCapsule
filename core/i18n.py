_CURRENT_LANG = "en"


def set_language(lang: str) -> str:
    global _CURRENT_LANG
    _CURRENT_LANG = lang if lang in _STRINGS else "en"
    return _CURRENT_LANG


def get_language() -> str:
    return _CURRENT_LANG


def tr(key: str, lang: str | None = None) -> str:
    l = lang if lang in _STRINGS else _CURRENT_LANG
    return _STRINGS.get(l, _STRINGS["uk"]).get(key, _STRINGS["uk"].get(key, key))
